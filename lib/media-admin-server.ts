import "server-only";

import { NextRequest, NextResponse } from "next/server";

/*
 * Server-side client of the media server's content-management API (/api/admin/content/*).
 * The admin token is added here and never leaves the server; the browser only talks to /api/admin/content/*.
 */

const NO_STORE = { "Cache-Control": "no-store" };
const REQUEST_TIMEOUT = 20_000;
const UPLOAD_TIMEOUT = 120_000;

function fail(status: number, message: string) {
  return NextResponse.json({ success: false, message }, { status, headers: NO_STORE });
}

function config() {
  const baseUrl = (process.env.MEDIA_API_URL || process.env.MEDIA_API_BASE)?.trim().replace(/\/+$/, "");
  const token = process.env.MEDIA_ADMIN_TOKEN?.trim();
  return baseUrl && token ? { baseUrl, token } : null;
}

/** Media links come back relative ("/api/media/..."); make them absolute here, on the server. */
function absolutize(value: unknown, baseUrl: string): unknown {
  if (Array.isArray(value)) return value.map((item) => absolutize(item, baseUrl));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [
        key,
        typeof item === "string" && /url$/i.test(key) && item.startsWith("/") && !item.startsWith("//")
          ? `${baseUrl}${item}`
          : absolutize(item, baseUrl),
      ])
    );
  }
  return value;
}

export async function forwardToMediaAdmin(request: NextRequest, upstreamPath: string, options: { upload?: boolean } = {}) {
  // Disconnected unless explicitly switched on: nothing is sent to the media server.
  if (process.env.NEXT_PUBLIC_CONTENT_MODE !== "live") return fail(503, "اتصال پیشخوان به سرور محتوا فعلاً قطع است.");

  const settings = config();
  if (!settings) return fail(500, "اتصال به سرور مدیریت محتوا هنوز پیکربندی نشده است.");

  const headers: Record<string, string> = { Accept: "application/json", Authorization: `Bearer ${settings.token}` };
  let body: BodyInit | undefined;

  if (request.method !== "GET" && request.method !== "DELETE") {
    const type = request.headers.get("content-type") || "";
    try {
      if (type.includes("multipart/form-data")) {
        // FormData goes forward as it is; the boundary header is generated by fetch.
        body = await request.formData();
      } else {
        body = await request.text();
        headers["Content-Type"] = "application/json";
      }
    } catch {
      return fail(400, "درخواست نامعتبر است.");
    }
  }

  let upstream: Response;
  try {
    upstream = await fetch(`${settings.baseUrl}${upstreamPath}`, {
      method: request.method,
      headers,
      body,
      cache: "no-store",
      signal: AbortSignal.timeout(options.upload ? UPLOAD_TIMEOUT : REQUEST_TIMEOUT),
    });
  } catch {
    return fail(502, "ارتباط با سرور مدیریت محتوا برقرار نشد. کمی بعد دوباره تلاش کنید.");
  }

  // 401/403 from upstream means the server token was rejected, not that the admin's session ended.
  if (upstream.status === 401 || upstream.status === 403) {
    return fail(502, "سرور مدیریت محتوا توکن را نپذیرفت. تنظیم MEDIA_ADMIN_TOKEN را در Vercel و سرور بررسی کنید.");
  }
  if (upstream.status === 204) return new NextResponse(null, { status: 204, headers: NO_STORE });

  const text = await upstream.text();
  let data: unknown;
  try {
    data = JSON.parse(text);
  } catch {
    return fail(502, "پاسخ سرور مدیریت محتوا قابل خواندن نبود.");
  }

  return NextResponse.json(absolutize(data, settings.baseUrl), { status: upstream.status, headers: NO_STORE });
}
